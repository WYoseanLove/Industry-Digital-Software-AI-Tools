import { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js';
import { StdioServerTransport } from '@modelcontextprotocol/sdk/server/stdio.js';
import { z } from 'zod';
import { fileURLToPath } from 'node:url';
import { RepositoryBridge } from './bridge.mjs';

const bridge = new RepositoryBridge();
const server = new McpServer({ name: 'industry-digital-software-ai-tools', version: '1.0.0' }, {
  instructions: 'First call repository_context and read all returned rules and relevant product manuals/Memory. Use only existing runners. Start environment detection, then successful product setup before generating/building skills. Poll every runner job to completion and read all output pages, including Memory. Do not infer success from a job ID. Never set authorized/userConfirmed/overwriteConfirmed without the user providing that authorization/approval. No elevation, arbitrary shell, automatic selection expansion, or unapproved data sharing.'
});
const product = z.enum(['NX', 'Office', 'Catia', 'Vismockup', 'Tecnomatix']);
const skill = z.string().regex(/^[A-Za-z][A-Za-z0-9_]{0,79}$/);
const annotations = { readOnlyHint: true, destructiveHint: false, openWorldHint: false };
const actionAnnotations = { readOnlyHint: false, destructiveHint: true, openWorldHint: false };
const textResult = value => ({ content: [{ type: 'text', text: JSON.stringify(value) }] });

function register(name, description, inputSchema, hints, handler) {
  server.registerTool(name, { description, inputSchema, annotations: hints }, async input => {
    try {
      return textResult(await handler(input));
    } catch (error) {
      return { isError: true, content: [{ type: 'text', text: error.message }] };
    }
  });
}

register('repository_context', 'Read repository startup context. This does not execute software. Read the rules and relevant manuals before using action tools.',
  {}, annotations, async () => {
    const files = ['README.md', '.github\\copilot-instructions.md', 'Memory\\learned.md', 'Memory\\INDEX.md', 'Memory\\task_workflow_rules.md'];
    const documents = [];
    for (const filename of files) {
      if (filename === 'Memory\\INDEX.md') {
        try { documents.push(await bridge.read(filename, 1, 1000)); }
        catch (error) {
          if (error.code !== 'ENOENT') throw error;
          documents.push({ path: filename, notice: 'Index is generated by the Memory gate. Call environment detection to generate it; list Memory to find topics meanwhile.' });
        }
      } else documents.push(await bridge.read(filename, 1, 1000));
    }
    return { root: bridge.root, documents, execution: 'Existing PowerShell runners only; no software operation has been executed.' };
  });
register('repository_read', 'Read a page of a repository text file. Paths are relative to this checkout; binary files and external paths are blocked.',
  { path: z.string().max(1000), startLine: z.number().int().min(1).default(1), lineCount: z.number().int().min(1).max(1000).default(200) },
  annotations, input => bridge.read(input.path, input.startLine, input.lineCount));
register('repository_list', 'List one repository directory, paginated. Does not recurse or follow external junctions.',
  { path: z.string().max(1000).default(''), offset: z.number().int().min(0).default(0), limit: z.number().int().min(1).max(200).default(100) },
  annotations, input => bridge.list(input.path, input.offset, input.limit));
register('skill_write', 'Write only product Task source/skill Markdown after successful setup. Read exact API references first. Markdown must be English first, Chinese second. Obtain approval before overwriting.',
  { product, skill, filename: z.string().max(120), content: z.string().max(1024 * 1024),
    overwriteConfirmed: z.boolean().default(false) }, actionAnnotations, input => bridge.writeSkill(input));
register('runner_start', 'Start the existing environment/product runner, without changing its implementation. Returns a job ID, NOT success. Poll runner_status and read all Memory/output pages. Setup/build state resets on server restart. Every run needs user approval; build/run also need software/API authorization.',
  { command: z.enum(['environment', 'setup', 'ping', 'build', 'run']), product: product.optional(), skill: skill.optional(),
    taskHint: z.string().min(1).max(2000), args: z.array(z.string().max(8000)).max(100).default([]),
    argsJson: z.record(z.string(), z.unknown()).default({}), timeoutSeconds: z.number().int().min(10).max(3600).default(120),
    authorized: z.boolean().default(false), userConfirmed: z.boolean().default(false) },
  actionAnnotations, input => {
    if ((input.command === 'build' || input.command === 'run') && !input.skill) throw new Error('Skill is required for build/run.');
    if (input.command !== 'environment' && !input.product) throw new Error('Product is required.');
    if (input.command !== 'run' && (input.args.length || Object.keys(input.argsJson).length)) {
      throw new Error('Skill arguments are only accepted for run.');
    }
    if (input.product === 'Tecnomatix' && input.args.length) throw new Error('Tecnomatix uses argsJson, not args.');
    if (input.product !== 'Tecnomatix' && Object.keys(input.argsJson).length) throw new Error('Only Tecnomatix uses argsJson; other products use args.');
    return bridge.start(input);
  });
register('runner_status', 'Poll a runner job and read output by character offset. Success requires status completed AND exitCode 0. Read until nextOffset reaches outputLength; failed jobs include errors.',
  { jobId: z.string().uuid(), offset: z.number().int().min(0).default(0),
    limit: z.number().int().min(1).max(32000).default(16000) }, annotations,
  input => bridge.status(input.jobId, input.offset, input.limit));

if (process.argv.includes('--print-config')) {
  process.stdout.write(`${JSON.stringify({ mcpServers: {
    'industry-digital-software': { command: process.execPath, args: [fileURLToPath(import.meta.url)] }
  } }, null, 2)}\n`);
} else {
  server.server.onclose = () => { void bridge.close(); };
  for (const signal of ['SIGINT', 'SIGTERM']) {
    process.once(signal, async () => {
      await bridge.close();
      await server.close();
    });
  }
  await server.connect(new StdioServerTransport());
}
