# Memory gate, dot-sourced by every runner (or run directly: memcheck.ps1 -MemScope NX -MemHint "weld LFO").
# Topic files in Memory/*.md carry a YAML front matter: title, scope (comma list or 'all'), triggers (comma list), always (true/false), updated.
# Selection per file:
#   always: true                                       -> printed in full
#   scope matches AND a trigger hits the task context  -> printed in full
#   scope matches, no trigger hit                      -> entry headings only (read the file if relevant)
#   scope does not match                               -> one-line listing
# Task context = $env:MFG_TASK_HINT + -MemHint + the runner arguments. Set MFG_TASK_HINT to the user's request keywords before calling a runner.
# Repository-configuration topic files live in Memory/*.md; product knowledge and run-produced ones live in Memory/Costomer/*.md (same format, same selection rules).
# Memory/INDEX.md is regenerated on every run. Exit 14 when the Memory folder or learned.md is missing.
# Keep this file ASCII-only (Windows PowerShell 5.1 without BOM).
param([string]$MemScope = '', [string]$MemHint = '')

function Get-MemFrontMatter([string[]]$Lines) {
    $fm = @{ title = ''; scope = ''; triggers = ''; always = 'false'; updated = '' }
    if ($Lines.Count -lt 3 -or $Lines[0].Trim([char]0xFEFF).Trim() -ne '---') { return $fm }
    for ($i = 1; $i -lt $Lines.Count; $i++) {
        if ($Lines[$i].Trim() -eq '---') { break }
        if ($Lines[$i] -match '^\s*([A-Za-z_]+)\s*:\s*(.*)$') { $fm[$Matches[1].ToLower()] = $Matches[2].Trim() }
    }
    return $fm
}

function Split-MemList([string]$s) {
    return @($s -split '[,;]' | ForEach-Object { $_.Trim() } | Where-Object { $_ })
}

function Test-MemFormat([string]$Name, [string[]]$Lines, $Fm) {
    $warn = @()
    foreach ($k in 'title', 'scope', 'triggers', 'updated') { if (-not $Fm[$k]) { $warn += "missing front matter field '$k'" } }
    $starts = @()
    for ($i = 0; $i -lt $Lines.Count; $i++) { if ($Lines[$i] -match '^## ') { $starts += $i } }
    for ($n = 0; $n -lt $starts.Count; $n++) {
        $end = $Lines.Count
        if ($n + 1 -lt $starts.Count) { $end = $starts[$n + 1] }
        $head = $Lines[$starts[$n]]
        if ($head -notmatch '^## [A-Z]{2,3}-\d+ ') { $warn += "bad entry heading '$head' (expected '## XX-01 title')"; continue }
        $body = ($Lines[($starts[$n] + 1)..($end - 1)] -join "`n")
        if ($body -notmatch '(?m)^- ') { $warn += "entry '$head' has no content lines" }
    }
    if ($starts.Count -eq 0) { $warn += 'no entries (## XX-01 title)' }
    foreach ($w in $warn) { Write-Host "[!]  Memory format: $Name - $w" }
}

function Update-MemIndex([string]$MemDir, $Topics) {
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine('# Memory INDEX (auto-generated by tools/memcheck.ps1, do not edit by hand)')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('learned.md = user traits + general/env corrections (always printed). Topic files below are selected by scope + triggers.')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('| File | Title | Scope | Always | Entries | Updated | Triggers |')
    [void]$sb.AppendLine('|---|---|---|---|---|---|---|')
    foreach ($t in $Topics) {
        [void]$sb.AppendLine("| $($t.Name) | $($t.Title) | $($t.Scope) | $($t.Always) | $($t.Entries) | $($t.Updated) | $($t.Triggers) |")
    }
    $text = $sb.ToString().TrimEnd() + "`r`n"
    $path = Join-Path $MemDir 'INDEX.md'
    $old = ''
    if (Test-Path -LiteralPath $path) { $old = [System.IO.File]::ReadAllText($path) }
    if ($old.TrimStart([char]0xFEFF) -ne $text) {
        [System.IO.File]::WriteAllText($path, $text, (New-Object System.Text.UTF8Encoding($true)))
    }
}

function Assert-Memory([string]$Scope, [string]$Hint = '') {
    try { [Console]::OutputEncoding = [System.Text.Encoding]::UTF8 } catch { }
    $repo = Split-Path -Parent $PSScriptRoot
    $mem = Join-Path $repo 'Memory'
    $learned = Join-Path $mem 'learned.md'
    if (-not (Test-Path -LiteralPath $learned)) {
        Write-Host "[X]  Memory gate: $learned not found. Restore the Memory folder before continuing."
        exit 14
    }

    $callerArgs = ''
    try { $callerArgs = (@(Get-Variable -Scope 1 -Name args -ValueOnly -ErrorAction Stop) -join ' ') } catch { }
    $ctx = (@($env:MFG_TASK_HINT, $Hint, $callerArgs) | Where-Object { $_ }) -join ' '

    $general = [regex]::Unescape('\u901a\u7528')
    $env_ = [regex]::Unescape('\u73af\u5883')
    $tags = @($general, $env_, $Scope) | ForEach-Object { [regex]::Escape($_) }
    $tagRx = '\[(' + ($tags -join '|') + ')\]'

    Write-Host "=== MEMORY GATE (scope: $Scope) - read and apply before acting ==="
    if ($ctx) { Write-Host "task context: $ctx" } else { Write-Host 'task context: (empty) - set $env:MFG_TASK_HINT to the request keywords for precise topic selection' }
    Write-Host "--- $learned (user traits + corrections filtered to scope) ---"
    foreach ($line in (Get-Content -LiteralPath $learned -Encoding UTF8)) {
        $isEntry = $line -match '^- \[\d{4}-\d{2}-\d{2}\] \['
        if (-not $isEntry -or $line -match $tagRx) { Write-Host $line }
    }

    $topics = @()
    $cust = Join-Path $mem 'Costomer'
    if (-not (Test-Path -LiteralPath $cust)) { New-Item -ItemType Directory -Path $cust -Force | Out-Null }
    $files = @(Get-ChildItem -LiteralPath $mem -Filter *.md -File | Where-Object { $_.Name -ne 'learned.md' -and $_.Name -ne 'INDEX.md' } | Sort-Object Name)
    $files += @(Get-ChildItem -LiteralPath $cust -Filter *.md -File | Sort-Object Name)
    foreach ($f in $files) {
        $rel = $f.Name
        if ($f.DirectoryName -eq $cust) { $rel = 'Costomer/' + $f.Name }
        $lines = @(Get-Content -LiteralPath $f.FullName -Encoding UTF8)
        $fm = Get-MemFrontMatter $lines
        Test-MemFormat $rel $lines $fm
        $entries = @($lines | Where-Object { $_ -match '^## [A-Z]{2,3}-\d+' })
        $topics += [pscustomobject]@{ Name = $rel; Title = $fm.title; Scope = $fm.scope; Always = $fm.always; Entries = $entries.Count; Updated = $fm.updated; Triggers = $fm.triggers }

        $scopes = Split-MemList $fm.scope
        $always = ($fm.always -eq 'true')
        $scopeHit = ($scopes.Count -eq 0) -or ($scopes -contains 'all') -or ($scopes -contains $Scope)
        $trigHit = @(Split-MemList $fm.triggers | Where-Object { $ctx.IndexOf($_, [System.StringComparison]::OrdinalIgnoreCase) -ge 0 })

        if ($always -or ($scopeHit -and $trigHit.Count -gt 0)) {
            $why = 'always'
            if (-not $always) { $why = 'triggers: ' + ($trigHit -join ', ') }
            Write-Host "--- $($f.FullName) [FULL; $why] ---"
            $lines | ForEach-Object { Write-Host $_ }
        } elseif ($scopeHit) {
            Write-Host "--- $($f.FullName) [scope match, no trigger hit: headings only; read the file if the task touches: $($fm.triggers)] ---"
            $lines | Where-Object { $_ -match '^## ' } | ForEach-Object { Write-Host $_ }
        } else {
            Write-Host "--- (other scope: $($fm.scope)) $($f.FullName) - $($fm.title)"
        }
    }
    try { Update-MemIndex $mem $topics } catch { Write-Host "[!]  Memory INDEX update failed: $($_.Exception.Message)" }
    Write-Host "=== END MEMORY GATE ==="
}

if ($MemScope) { Assert-Memory $MemScope $MemHint }
